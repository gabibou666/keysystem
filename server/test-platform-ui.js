'use strict';
const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const { startFixture } = require('./tests/platform-fixture');
async function run() {
  const f=await startFixture();
  const browser=await chromium.launch({headless:true});
  const artifacts=path.join(__dirname,'../artifacts/platform');fs.mkdirSync(artifacts,{recursive:true});
  try {
    const context=await browser.newContext({locale:'en-US',viewport:{width:1440,height:1000},reducedMotion:'reduce'});
    const page=await context.newPage(),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(f.base);await page.locator('#cookieConsentReject').click();await page.screenshot({path:path.join(artifacts,'home-desktop.png'),fullPage:true});
    assert.equal((await page.getByRole('heading',{level:1}).textContent()).replace(/\s+/g,''),'Yourscripts.Yourrules.');
    await page.getByText('How do I create a developer account?').click();
    assert.equal(await page.locator('details[open]').count(),1);
    assert.equal(await page.locator('.workspace-capture img').count(),1,'The landing uses an actual dashboard capture');
    assert.equal(await page.locator('.workspace-capture img').getAttribute('loading'),'lazy','The dashboard screenshot loads below the fold');
    assert.equal(await page.locator('.release-workflow li').count(),4,'One four-step release workflow remains');
    assert.equal(await page.locator('[data-demo]').count(),0,'Repeated sample-data previews have been replaced');
    await page.goto(f.base+'/signup');
    await page.locator('#emailStatus').waitFor({state:'visible'});
    assert.equal(await page.locator('#submitAuth').isDisabled(),true);
    await page.screenshot({path:path.join(artifacts,'signup-desktop.png'),fullPage:true});
    process.env.RESEND_API_KEY='test-only';process.env.AUTH_EMAIL_FROM='test@example.com';
    const fixtureFetch=global.fetch;const mailbox=[];
    global.fetch=async(url,options)=>{if(String(url)==='https://api.resend.com/emails') {mailbox.push(JSON.parse(options.body));return new Response('{"id":"test"}',{status:200});}return fixtureFetch(url,options);};
    await page.reload();
    await page.getByLabel('Your name',{exact:true}).fill('UI Email Developer');
    await page.getByLabel('Email address',{exact:true}).fill('ui@example.com');
    await page.locator('#passwordInput').fill('ui-test-strong-password');
    assert.equal(await page.locator('#acceptedTerms').isChecked(),false,'Legal agreement is never preselected');
    await page.locator('#acceptedTerms').check();
    await page.locator('#submitAuth').click();
    await page.getByText('Check your email to verify your account.',{exact:false}).waitFor();
    const verifyUrl=mailbox[0].text.match(/https?:\/\/\S+/)[0];
    await page.goto(verifyUrl);
    assert.equal(new URL(page.url()).search,'','One-time token cleared from address bar');
    await page.locator('#submitAuth').click();await page.locator('#successLogin').waitFor({state:'visible'});
    await page.locator('#successLogin').click();
    await page.getByLabel('Email address',{exact:true}).fill('ui@example.com');
    await page.locator('#passwordInput').fill('ui-test-strong-password');
    await page.locator('#submitAuth').click();await page.locator('#workspaceView').waitFor({state:'visible'});
    await page.locator('#logoutBtn').click();await page.locator('#loginView').waitFor({state:'visible'});
    global.fetch=fixtureFetch;
    await page.goto(f.base+'/dashboard');await page.getByText('Sign in to your account').waitFor();
    await page.screenshot({path:path.join(artifacts,'login-desktop.png')});
    await context.addCookies([{name:'ah_session',value:f.cookies[0].slice('ah_session='.length),url:f.base}]);
    await page.reload();await page.getByText('Make room for your first release.').waitFor();
    await page.getByRole('button',{name:'New project',exact:true}).click();
    await page.getByLabel('Project name',{exact:true}).last().fill('My <test> project');
    await page.getByRole('button',{name:'Create project',exact:true}).click();
    await page.getByRole('heading',{name:'Project API token',exact:true}).waitFor();
    assert.match(await page.locator('#secretOutput').inputValue(),/^ahp_/);
    await page.locator('#secretDialog [data-close-dialog]').click();
    await page.locator('[data-view="licenses"]').click();
    await page.getByRole('button',{name:'Issue licenses',exact:true}).click();
    await page.getByRole('button',{name:'Generate keys',exact:true}).click();
    await page.getByRole('heading',{name:'Save your licenses',exact:true}).waitFor();
    const key=await page.locator('#secretOutput').inputValue();assert.match(key,/^ah_/);
    await page.locator('#secretDialog [data-close-dialog]').click();
    await page.locator('#licensesBody tr').first().getByText('Active',{exact:true}).waitFor();
    await page.locator('#licensesBody').getByRole('button',{name:'Revoke',exact:true}).click();
    await page.locator('#licensesBody tr').first().getByText('Revoked',{exact:true}).waitFor();
    await page.locator('[data-view="script"]').click();
    await page.locator('#scriptContent').fill('return "ui-test-script"');
    await page.getByRole('button',{name:'Publish script',exact:true}).click();
    await page.getByText('Build saved successfully. Your loader URL stays the same.',{exact:false}).waitFor();
    await page.locator('[data-view="settings"]').click();
    await page.getByLabel('Project name',{exact:true}).first().fill('My launch');
    await page.getByRole('button',{name:'Save settings',exact:true}).click();
    await page.getByText('Project settings saved.').waitFor();
    await page.locator('[data-view="checkpoints"]').click();
    assert.equal(await page.locator('#checkpointEditor').isVisible(),true,'New connection shows only the short setup form');
    assert.equal(await page.locator('#checkpointResult').isVisible(),false,'No share prompt before a provider is configured');
    assert.equal(await page.locator('#checkpointCount').isVisible(),false,'Optional task count starts collapsed');
    await page.screenshot({path:path.join(artifacts,'checkpoint-connect-desktop.png'),fullPage:true});
    await page.locator('#checkpointToken').fill('ui-lootlabs-token');
    await page.locator('#checkpointForm button[type="submit"]').click();
    await page.getByText('LootLabs connected',{exact:true}).waitFor();
    assert.equal(await page.locator('#checkpointEditor').isVisible(),false,'Saved connection hides setup fields');
    assert.equal(await page.locator('#copyClaimBtn').isVisible(),true,'Saved connection offers the user link immediately');
    const callbackUrl=await page.locator('#checkpointCallbackUrl').inputValue();
    assert.match(callbackUrl,/\/postback\?secret=[a-f0-9]{64}$/);
    assert.equal(await page.locator('#copyCheckpointCallbackBtn').isEnabled(),true);
    assert.equal(await page.locator('#secretDialog').isVisible(),false,'Callback is available inline without a one-time dialog');
    const checkpointProject=await page.locator('#projectSelect').inputValue();
    await page.reload();await page.locator('#workspaceView').waitFor({state:'visible'});
    await page.locator('#projectSelect').selectOption(checkpointProject);
    await page.locator('[data-view="checkpoints"]').click();
    await page.getByText('LootLabs connected',{exact:true}).waitFor();
    assert.equal(await page.locator('#checkpointCallbackUrl').inputValue(),callbackUrl,'Callback survives a page reload');
    assert.equal(await page.locator('#checkpointToken').getAttribute('required'),null,'Saved credentials do not need to be entered again');
    await page.locator('#editCheckpointBtn').click();
    await page.locator('#checkpointForm button[type="submit"]').click();
    await page.getByText('LootLabs saved.',{exact:false}).waitFor();
    assert.equal(await page.locator('#checkpointCallbackUrl').inputValue(),callbackUrl,'Saving keeps the callback stable');
    await context.grantPermissions(['clipboard-read','clipboard-write']);
    await page.locator('#copyCheckpointCallbackBtn').click();
    await page.locator('#checkpointCopyMessage').getByText('Copied.',{exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),callbackUrl,'Copy button puts the callback URL on the clipboard');
    await page.locator('#copyClaimBtn').click();
    await page.locator('#checkpointShareMessage').getByText('Copied.',{exact:true}).waitFor();
    assert.match(await page.evaluate(()=>navigator.clipboard.readText()),/\/claim\?project=/,'Primary copy button shares the public page, not the private callback');
    await page.screenshot({path:path.join(artifacts,'checkpoint-setup-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,'Checkpoint setup has no mobile overflow');
    await page.screenshot({path:path.join(artifacts,'checkpoint-setup-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('#editCheckpointBtn').click();
    await page.locator('#checkpointProvider').selectOption('workink');
    assert.equal(await page.locator('#checkpointLinkField').isVisible(),true);
    assert.equal(await page.locator('#checkpointLinkIdField').isVisible(),true);
    assert.equal(await page.locator('#checkpointTokenField').isVisible(),false);
    await page.locator('#checkpointLinkUrl').fill('https://work.ink/123/example');
    await page.locator('#checkpointLinkId').fill('10345');
    await page.locator('#checkpointForm button[type="submit"]').click();
    await page.getByText('Work.ink connected').waitFor();
    assert.equal(await page.locator('#checkpointCallbackField').isVisible(),true,'Automatic provider still exposes its callback');
    assert.match(await page.locator('#checkpointCallbackUrl').inputValue(),/\/return\?token=\{TOKEN\}$/,'Work.ink callback includes the documented token macro');
    assert.match(await page.locator('#checkpointCallbackTitle').textContent(),/automatically/,'Automatic callback needs no extra manual step');
    assert.equal(await page.locator('#checkpointEditor').isVisible(),false,'Work.ink save also returns directly to sharing');
    await page.locator('#editCheckpointBtn').click();
    await page.locator('#checkpointProvider').selectOption('linkvertise');
    assert.equal(await page.locator('#checkpointLinkIdField').isVisible(),false);
    assert.equal(await page.locator('#checkpointTokenField').isVisible(),true);
    assert.equal(await page.locator('#linkvertiseTargetField').isVisible(),true);
    assert.match(await page.locator('#linkvertiseTargetUrl').inputValue(),/\/api\/platform\/checkpoints\/.+\/return$/);
    await page.locator('#cancelCheckpointEditBtn').click();
    assert.equal(await page.locator('#checkpointEditor').isVisible(),false,'Cancel restores the saved connection summary');
    await page.locator('#editCheckpointBtn').click();
    await page.locator('#checkpointProvider').selectOption('linkunlocker');
    await page.locator('#checkpointLinkUrl').fill('https://linkunlocker.com/u/example');
    await page.locator('#checkpointToken').fill('d'.repeat(64));
    await page.locator('#checkpointForm button[type="submit"]').click();
    await page.getByText('LinkUnlocker connected',{exact:true}).waitFor();
    assert.match(await page.locator('#checkpointCallbackUrl').inputValue(),/\/return$/,'LinkUnlocker return endpoint is displayed');
    assert.match(await page.locator('#checkpointHelp').textContent(),/base URL alone cannot complete/,'Dynamic callback limitations are explained');
    await page.screenshot({path:path.join(artifacts,'checkpoints-desktop.png'),fullPage:true});
    await page.locator('[data-view="overview"]').click();
    await page.getByRole('heading',{name:'My launch',exact:true}).waitFor();
    await page.screenshot({path:path.join(artifacts,'dashboard-desktop.png'),fullPage:true});
    for(const route of ['/', '/dashboard','/docs','/claim','/signup','/login','/verify-email','/reset-password']) {
      await page.setViewportSize({width:390,height:844});await page.goto(f.base+route);
      if(route==='/dashboard')await page.locator('#workspaceView').waitFor({state:'visible'});
      const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
      assert.equal(overflow,false,'No mobile overflow on '+route);
      await page.screenshot({path:path.join(artifacts,(route==='/'?'home':route.slice(1))+'-mobile.png'),fullPage:true});
    }
    assert.deepEqual(errors,[],'No browser JavaScript errors');
    console.log('Platform UI: landing, sign-in state, project creation, issuance, revocation, publication, settings email signup and verification, product previews and eight mobile layouts passed.');
    console.log('Screenshots: '+artifacts);
  } finally {await browser.close();await f.close();}
}
run().catch(e=>{console.error(e.message);process.exitCode=1;});
